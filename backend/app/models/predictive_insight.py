import uuid
from datetime import datetime, timezone, date
from sqlalchemy import Column, String, Text, Float, Boolean, Date, DateTime, JSON, Index
from backend.app.database import Base

def utc_now():
    return datetime.now(timezone.utc)

class PredictiveInsight(Base):
    """
    Stores predictive intelligence observations generated by Phase 4.5.
    Records forward-looking risk assessments, confidence metrics,
    contributing factors, and tracks prediction horizon evaluations against actual outcomes.
    """
    __tablename__ = "predictive_insights"

    id = Column(String(50), primary_key=True, default=lambda: f"pred_{uuid.uuid4().hex[:12]}")
    prediction_type = Column(String(50), nullable=False, index=True)
    # Types: DEADLINE_RISK, GOAL_TRAJECTORY, WORKLOAD_OVERLOAD, HABIT_DECAY, WORKLOAD_FEASIBILITY, PRODUCTIVITY_TREND

    entity_type = Column(String(30), nullable=False, index=True)  # Task, Goal, Habit, Workload, System
    entity_id = Column(String(100), nullable=True, index=True)

    risk_score = Column(Float, nullable=False, default=0.0)       # 0.0 to 100.0
    risk_category = Column(String(20), nullable=False, index=True) # LOW, MODERATE, HIGH, CRITICAL, INSUFFICIENT_DATA
    confidence_score = Column(Float, nullable=False, default=0.0) # 0.0 to 1.0 (statistical rigor score)
    has_sufficient_data = Column(Boolean, nullable=False, default=True)

    title = Column(String(200), nullable=False)
    summary = Column(Text, nullable=False)
    supporting_evidence = Column(JSON, nullable=True)             # List[str] of empirical facts
    contributing_factors = Column(JSON, nullable=True)            # List[str] of primary drivers
    suggested_action = Column(Text, nullable=True)

    time_horizon = Column(String(100), nullable=True)             # e.g. "Next 48 Hours", "Next 7 Days"
    horizon_date = Column(Date, nullable=True, index=True)        # Exact date when horizon matures

    # Evaluation tracking against actual future outcomes
    predicted_outcome = Column(String(100), nullable=True)
    actual_outcome = Column(String(100), nullable=True)
    evaluation_status = Column(String(30), nullable=False, default="PENDING", index=True)
    # Statuses: PENDING, EVALUATED, INSUFFICIENT_DATA, EXPIRED
    evaluation_notes = Column(Text, nullable=True)
    model_version = Column(String(50), nullable=False, default="statistical_v1")

    created_at = Column(DateTime, nullable=False, default=utc_now)
    updated_at = Column(DateTime, nullable=False, default=utc_now, onupdate=utc_now)
    evaluated_at = Column(DateTime, nullable=True)

    __table_args__ = (
        Index("ix_predictive_type_entity", "prediction_type", "entity_id"),
        Index("ix_predictive_status_horizon", "evaluation_status", "horizon_date"),
    )

    def __repr__(self) -> str:
        return f"<PredictiveInsight {self.id}: [{self.prediction_type}] {self.risk_category} (conf={self.confidence_score:.2f})>"
